KS.getP = function (path) {
  const a = path.split('.'); let v = KS.P;
  for (let i = 0; i < a.length; i++) v = v[a[i]];
  return v;
};

KS.setP = function (path, val) {
  const a = path.split('.'); let o = KS.P;
  for (let i = 0; i < a.length - 1; i++) o = o[a[i]];
  o[a[a.length - 1]] = val;
};
